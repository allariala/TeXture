from capture_security import MAX_UPLOAD_BYTES, decode_capture, valid_token  # noqa: E402
from model_integrity import MODEL_SHA256  # noqa: E402 (generated by the build)

# Inference is compute-bound: physical cores are faster than all logical ones (less contention).
torch.set_num_threads(max(1, (os.cpu_count() or 2) // 2))

# v1 assigned the *module* attribute, so load_processor() (which reads the settings object) still went to
# Hugging Face for the tokenizer. Point the settings object at the bundled folder.
texify_settings.settings.MODEL_CHECKPOINT = MODEL_DIR


def _patched_get_config(model_checkpoint):
    """texify 0.2 / newer transformers config compatibility."""
    with open(os.path.join(model_checkpoint, "model_config.json"), encoding="utf-8") as stream:
        config = VisionEncoderDecoderConfig.from_dict(json.load(stream))
    encoder = getattr(config, "encoder", {})
    if not isinstance(encoder, dict):
        encoder = encoder.to_dict() if hasattr(encoder, "to_dict") else vars(encoder)
    decoder = getattr(config, "decoder", {})
    if not isinstance(decoder, dict):
        decoder = decoder.to_dict() if hasattr(decoder, "to_dict") else vars(decoder)
    config.encoder = texify_config.VariableDonutSwinConfig(**encoder)
    if hasattr(transformers, "DonutSwinConfig") and isinstance(decoder, dict) and "donut-swin" in decoder.get("model_type", ""):
        config.decoder = transformers.DonutSwinConfig(**decoder)
    return config


texify_config.get_config = _patched_get_config

_clients = set()
_clients_lock = threading.Lock()
_infer_lock = threading.Lock()

class OfflineProcessor:
    """Explicit local components; no AutoProcessor or downloaded Python modules."""
    def __init__(self):
        with open(os.path.join(MODEL_DIR, "preprocessor_config.json"), encoding="utf-8") as stream:
            params = json.load(stream)
        params["size"] = {"height": 420, "width": 420}
        self.image_processor = VariableDonutImageProcessor(**params)
        self.image_processor.max_size = {"height": 420, "width": 420}
        self.image_processor.size = {"height": 420, "width": 420}
        self.image_processor.train = False
        with open(os.path.join(MODEL_DIR, "special_tokens_map.json"), encoding="utf-8") as stream:
            special = json.load(stream)
        special = {key: value["content"] if isinstance(value, dict) else value for key, value in special.items()}
        self.tokenizer = PreTrainedTokenizerFast(tokenizer_file=os.path.join(MODEL_DIR, "tokenizer.json"),
                                                model_max_length=384, **special)

    def __call__(self, images, **kwargs):
        return self.image_processor(images, **kwargs)


processor = OfflineProcessor()
weights_path = os.path.join(BASE, "texify_weights.pt")
with open(weights_path, "rb") as stream:
    if hashlib.file_digest(stream, "sha256").hexdigest() != MODEL_SHA256:
        raise RuntimeError("OCR model integrity check failed; reinstall TeXture")
config = _patched_get_config(MODEL_DIR)
AutoModel.register(texify_config.VariableDonutSwinConfig, VariableDonutSwinModel, exist_ok=True)
model = GenerateVisionEncoderDecoderModel(config)
model = torch.ao.quantization.quantize_dynamic(model, {torch.nn.Linear}, dtype=torch.qint8)
model.load_state_dict(torch.load(weights_path, map_location="cpu", weights_only=True))
model.eval()


def _recognise(img):
    with _infer_lock, torch.inference_mode():
        return batch_inference([img], model, processor)[0]


def _clean_latex(text):
    text = text.strip()
    if text.startswith("\\[") and text.endswith("\\]"):
        text = text[2:-2].strip()
    text = text.replace("$", "").replace("\\(", "").replace("\\)", "")
    return re.sub(r"\s+", " ", text).strip()


# Warm-up: the first inference allocates buffers and is several times slower; do it before reporting
# ready, so the user's first capture is fast.
try:
    _recognise(Image.new("RGB", (160, 48), "white"))
except Exception:
    pass

app = FastAPI(docs_url=None, redoc_url=None, openapi_url=None)


@app.middleware("http")
async def _require_token(request: Request, call_next):
    if not valid_token(TOKEN, request.headers.get("x-texture-token")):
        return JSONResponse({"success": False, "error": "forbidden"}, status_code=403)
    # Loopback-only service: reject browser-origin requests even with a guessed port.
    if request.headers.get("origin"):
        return JSONResponse({"success": False, "error": "forbidden"}, status_code=403)
    return await call_next(request)


@app.get("/")
def health():
    return {"status": "ok", "api": 3}


@app.post("/attach")
def attach(pid: int):
    if pid <= 0 or not _process_alive(pid):
        return JSONResponse({"success": False, "error": "invalid client"}, status_code=400)
    with _clients_lock:
        _clients.add(pid)
    return {"success": True}


@app.post("/predict")
async def predict(request: Request):
    try:
        if request.headers.get("content-type", "").split(";")[0].strip() != "image/png":
            return JSONResponse({"success": False, "error": "PNG required"}, status_code=415)
        data = bytearray()
        async for chunk in request.stream():
            if len(data) + len(chunk) > MAX_UPLOAD_BYTES:
                return JSONResponse({"success": False, "error": "Capture exceeds 32 MB"}, status_code=413)
            data.extend(chunk)
        # Decoding and inference run off the event loop so health checks remain responsive.
        from starlette.concurrency import run_in_threadpool
        def work():
            with decode_capture(data) as img:
                return _clean_latex(_recognise(img))
        return {"success": True, "latex": await run_in_threadpool(work)}
    except Exception as e:  # reported to the add-in, which shows it to the user
        return {"success": False, "error": str(e)}


def _process_alive(pid):
    if os.name != "nt":
        try:
            os.kill(pid, 0)
            return True
        except OSError:
            return False
    kernel32 = ctypes.windll.kernel32
    handle = kernel32.OpenProcess(0x00100000, False, pid)  # SYNCHRONIZE
    if not handle:
        return False
    try:
        return kernel32.WaitForSingleObject(handle, 0) == 0x102  # WAIT_TIMEOUT: still running
    finally:
        kernel32.CloseHandle(handle)


def _watchdog():
    while True:
        time.sleep(2)
        with _clients_lock:
            _clients.intersection_update({p for p in _clients if _process_alive(p)})
            if not _clients:
                os._exit(0)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=8000)
    args, _ = parser.parse_known_args()

    parent = os.environ.get("TEXTURE_PARENT_PID", "")
    if parent.isdigit():
        _clients.add(int(parent))
        threading.Thread(target=_watchdog, daemon=True).start()

    uvicorn.run(app, host="127.0.0.1", port=args.port, log_config=None, access_log=False,
                limit_concurrency=8, timeout_keep_alive=2)
